/** Single validated inventory; input order is immaterial to identity and execution. */
class OperationCatalog(definitions:List<OperationDefinition> = defaultDefinitions()) {
    val definitions:List<OperationDefinition> = definitions.toList()
    val discovery:List<OperationDefinition> = definitions.sortedBy { it.displayOrder }
    private val byId = definitions.associateBy { it.id }
    private val byName = definitions.associateBy { it.name }
    init {
        fun <T> unique(field:String, values:List<T>) { require(values.distinct().size == values.size) { "operation.duplicate_$field" } }
        unique("id",definitions.map { it.id })
        unique("name",definitions.map { it.name })
        unique("code",definitions.map { it.operationCode })
        unique("legacyIndex",definitions.map { it.legacyIndex })
        unique("displayOrder",definitions.map { it.displayOrder })
        require(byId.keys == OperationId.entries.toSet()) { "operation.missing_definition" }
        definitions.forEach { d ->
            require(d.execution != null) { "operation.missing_execution:${d.id}" }
            if(d.write) {
                require(d.execution in setOf(ExecutionStrategy.DIRECT_WRITE,ExecutionStrategy.PROFILE_BATCH)) { "operation.invalid_write_execution:${d.id}" }
                require(d.readSource == null) { "operation.invalid_write_source:${d.id}" }
                require(d.scope != null && d.confirmation != null && d.verification != null) { "operation.missing_write_policy:${d.id}" }
                if(d.execution == ExecutionStrategy.PROFILE_BATCH) {
                    require(d.scope == ScopeStrategy.PROFILE_CHILDREN && d.verification == VerificationStrategy.CHILD_PERSISTED_READBACK && d.receiptPolicy == ReceiptPolicy.BATCH_CHILD_PERSISTED_READBACK) { "operation.invalid_composite:${d.id}" }
                } else require(d.scope == ScopeStrategy.DIRECT && d.verification == VerificationStrategy.DIRECT) { "operation.invalid_direct:${d.id}" }
            } else {
                val expected=when(d.execution) {
                    ExecutionStrategy.SOURCE -> ReadStrategy.SOURCE to ReceiptPolicy.SOURCE_READ
                    ExecutionStrategy.COMPUTATION -> ReadStrategy.PURE_COMPUTATION to ReceiptPolicy.COMPUTATION
                    ExecutionStrategy.CATALOG -> ReadStrategy.CATALOG to ReceiptPolicy.CATALOG_READ
                    ExecutionStrategy.PLAN -> ReadStrategy.IN_MEMORY_PLAN to ReceiptPolicy.IN_MEMORY_PLAN
                    else -> throw IllegalArgumentException("operation.invalid_read_execution:${d.id}")
                }
                require(d.readSource == expected.first && d.receiptPolicy == expected.second && d.confirmation != null && d.scope == null && d.verification == null) { "operation.missing_read_source:${d.id}" }
            }
        }
    }
    operator fun get(id:OperationId):OperationDefinition = byId.getValue(id)
    fun find(name:String):OperationDefinition? = byName[name]
    companion object { fun defaultDefinitions():List<OperationDefinition> = OperationSchemas.definitions() }
}

